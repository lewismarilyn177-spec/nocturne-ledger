export function parseLevel(levelData, tileSize) {
  const walls = [];
  const walkable = [];
  for (let y = 0; y < levelData.map.length; y++) {
    const row = levelData.map[y];
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      const wx = x * tileSize + tileSize / 2;
      const wy = y * tileSize + tileSize / 2;
      if (ch === '#') {
        walls.push({ x: wx, y: wy, tileX: x, tileY: y });
      } else {
        walkable.push({ x: wx, y: wy, tileX: x, tileY: y });
      }
    }
  }
  return { walls, walkable };
}